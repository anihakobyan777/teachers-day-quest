# Ծրագրի տրամաբանություն
if 'current_teacher' not in st.session_state:
    st.title("🎓 12-րդ ԱԲ-ի Հատուկ Գործողությունը")
    st.write("Սիրելի ուսուցիչներ, ձեր շնորհավորանքներն ու անակնկալները ստանալու համար ընտրեք Ձեր անունը ստորև։")
    selected_teacher = st.selectbox("Ընտրեք Ձեր անունը", list(quiz_data.keys()))
    if st.button("Սկսել Կվեստը"):
        st.session_state.current_teacher = selected_teacher
        st.rerun()
else:
    teacher = st.session_state.current_teacher
    st.title(f"Կվեստ՝ {teacher}")
    
    # Թեստի հարցեր
    for i, item in enumerate(quiz_data[teacher]["questions"]):
        st.write(f"**Հարց {i+1}:** {item['q']}")
        choice = st.radio("", item['options'], key=f"q{i}", label_visibility="collapsed")
        if st.button(f"Ստուգել պատասխանը {i+1}", key=f"b{i}"):
            if item['options'].index(choice) == item['ans']:
                st.success("Ճիշտ է! ✅")
            else:
                st.error("Սխալ է, բայց դա ոչինչ չի փոխում :)")
        st.divider()

    if st.button("Ավարտել և ստանալ շնորհավորանքը"):
        st.balloons()
        st.success(quiz_data[teacher]["message"])
        if st.button("Վերադառնալ սկզբին"):
            del st.session_state.current_teacher
            st.rerun()
